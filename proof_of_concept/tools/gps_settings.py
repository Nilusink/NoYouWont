import serial

ser = serial.Serial("/dev/serial0", 115200, timeout=1)

# UBX command: set rate to 200ms (5Hz)
set_rate_5hz = bytes([
    0xB5, 0x62,       # header
    0x06, 0x08,       # CFG-RATE
    0x06, 0x00,       # payload length
    0xC8, 0x00,       # measRate = 200ms
    0x01, 0x00,       # navRate
    0x01, 0x00,       # timeRef
    0xDE, 0x6A        # checksum
])

set_rate_10hz = bytes([
    0xB5, 0x62, 0x06, 0x08, 0x06, 0x00,
    0x64, 0x00,   # 100 ms → 10 Hz
    0x01, 0x00,
    0x01, 0x00,
    0x7A, 0x12
])

set_baud_115200 = bytes([
    0xB5,0x62,0x06,0x00,0x14,0x00,
    0x01,0x00,0x00,0x00,
    0xD0,0x08,0x00,0x00,   # 115200
    0x00,0xC2,0x01,0x00,
    0x07,0x00,0x03,0x00,
    0x00,0x00,
    0x00,0x00,
    0xC0,0x7E
])

ser.write(set_rate_10hz)
